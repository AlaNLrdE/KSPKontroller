// iOS start-up glue for KSP HMI (docs/development/ios.rst). It runs as a static constructor, before SDL2main's
// UIApplicationMain and before hmi-cpp's main() (renamed SDL_main by SDL.h), so the shared code needs no iOS
// branch: everything here reaches it through the same environment variables the other platforms use.
//
//  - KSPHMI_APP_DIR: the bundle's hmi/ folder (config.toml + assets/, read-only).
//  - KSPHMI_LOCAL_CONFIG: Documents/config.local.toml, rewritten at every launch from the iOS Settings page
//    (Settings.bundle): PC address, game, skin, first flight scene. Broadcast discovery is always off: iOS
//    refuses UDP broadcast without the multicast entitlement, which a free Apple ID cannot get.
//  - SDL hints (environment form): both orientations, screen kept awake, home indicator dimmed.
//  - KSPHMISceneDelegate: the UIScene lifecycle iOS 27 requires (see the comment above the class).
//  - ksphmi_platform_safe_insets(): the window safe area for hmi-cpp (include/safearea.hpp), at the end.
#import <Foundation/Foundation.h>
#import <UIKit/UIKit.h>
#import <objc/runtime.h>

#include <cmath>
#include <cstdlib>

namespace {

/// A settings value when it is one of the allowed ones, else the fallback.
NSString* choice(NSUserDefaults* d, NSString* key, NSArray<NSString*>* allowed, NSString* fallback) {
    NSString* v = [d stringForKey:key];
    return v && [allowed containsObject:v] ? v : fallback;
}

/// The PC address typed in Settings, trimmed; nil when empty or not a plain host name / IPv4 address (it is
/// written into a TOML string, so only letters, digits, '.', '-' and '_' are accepted).
NSString* pc_host(NSUserDefaults* d) {
    NSString* v = [[d stringForKey:@"pc_host"]
        stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceAndNewlineCharacterSet];
    if (v.length == 0 || v.length > 253) return nil;
    NSCharacterSet* ok = [NSCharacterSet
        characterSetWithCharactersInString:@"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-_"];
    if ([v rangeOfCharacterFromSet:ok.invertedSet].location != NSNotFound) {
        NSLog(@"KSP HMI: ignoring PC address with unsupported characters");
        return nil;
    }
    return v;
}

/// hmi/ inside the bundle: at its root or under Resources/, depending on how CMake laid out the flat iOS bundle.
NSString* app_dir() {
    NSString* root = NSBundle.mainBundle.bundlePath;
    for (NSString* sub in @[ @"hmi", @"Resources/hmi" ]) {
        NSString* dir = [root stringByAppendingPathComponent:sub];
        if ([NSFileManager.defaultManager fileExistsAtPath:[dir stringByAppendingPathComponent:@"config.toml"]])
            return dir;
    }
    NSLog(@"KSP HMI: config.toml not found in the app bundle");
    return root;
}

NSString* local_config(NSUserDefaults* d) {
    NSString* host = pc_host(d);
    NSString* source = choice(d, @"source", @[ @"krpc", @"redux", @"auto", @"demo" ], @"krpc");
    NSString* skin =
        choice(d, @"skin", @[ @"auto", @"ksp1", @"ksp2", @"apollo", @"classic", @"steampunk" ], @"auto");
    NSString* scene = choice(d, @"flight_scene", @[ @"cockpit", @"instruments", @"mechjeb" ], @"cockpit");
    NSMutableString* t = [NSMutableString string];
    [t appendString:@"# Generated by KSP HMI at every launch from the iOS Settings app: edit the settings, not this file.\n"];
    [t appendFormat:@"source = \"%@\"\n\n[krpc]\ndiscovery = false\n", source];
    if (host) [t appendFormat:@"address = \"%@\"\n", host];
    [t appendFormat:@"\n[display]\noutput = \"sdl\"\nfullscreen = true\nskin = \"%@\"\nflight_scene = \"%@\"\n",
                    skin, scene];
    return t;
}

__attribute__((constructor)) void ksphmi_ios_prepare() {
    @autoreleasepool {
        setenv("KSPHMI_APP_DIR", app_dir().fileSystemRepresentation, 1);

        NSString* docs =
            NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask, YES).firstObject;
        if (docs) {
            NSString* path = [docs stringByAppendingPathComponent:@"config.local.toml"];
            NSError* error = nil;
            if ([local_config(NSUserDefaults.standardUserDefaults) writeToFile:path
                                                                    atomically:YES
                                                                      encoding:NSUTF8StringEncoding
                                                                         error:&error])
                setenv("KSPHMI_LOCAL_CONFIG", path.fileSystemRepresentation, 1);
            else
                NSLog(@"KSP HMI: cannot write %@: %@", path, error.localizedDescription);
        }

        // Same list as UISupportedInterfaceOrientations in Info.plist.in; a rotation arrives as
        // SDL_WINDOWEVENT_SIZE_CHANGED, which already rebuilds Canvas and Display in main.cpp.
        setenv("SDL_IOS_ORIENTATIONS", "LandscapeLeft LandscapeRight Portrait", 0);
        setenv("SDL_IOS_IDLE_TIMER_DISABLED", "1", 0);   // a flight display must not lock the screen
        setenv("SDL_IOS_HIDE_HOME_INDICATOR", "2", 0);   // dimmed; swipes still reach the system
    }
}

}  // namespace

// --- UIScene lifecycle (iOS 27) --------------------------------------------------------------------------------
// iOS 27 traps (EXC_BREAKPOINT in _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption) about a second
// after launch when an app does not adopt UIScene. SDL 2.32 still uses the app-delegate lifecycle only, so
// Info.plist.in declares UIApplicationSceneManifest with this delegate (name must match UISceneDelegateClassName).
//
// Under scenes a UIWindow without a windowScene is never shown, and SDL creates its window with
// -[SDL_uikitwindow initWithFrame:] from SDL_main (postFinishLaunch, after didFinishLaunching), so the order
// against scene:willConnectToSession: is not fixed. Both orders are handled:
//  - a window SDL already made before the scene connects is attached in scene:willConnectToSession:;
//  - for later ones, SDL_uikitwindow (only SDL's class, not UIWindow, so UIKit's own windows are untouched)
//    gets an -initWithFrame: that calls the inherited one and then sets the known scene. A notification cannot
//    do this: the window is created, made key and visible inside one SDL call with no notification in between
//    that fires for a sceneless window. SDL's sources stay unpatched.
// Sizes, rotation (SDL_WINDOWEVENT_SIZE_CHANGED from SDL's view controller) and touches work per window, as
// before. Background/foreground needs no forwarding: SDL listens to the UIApplication notifications
// (DidBecomeActive, WillResignActive, DidEnterBackground, WillEnterForeground), which UIKit still posts for a
// single-scene app; forwarding the scene callbacks too would deliver every SDL_APP_* event twice.

static __weak UIWindowScene* ksphmi_scene = nil;

namespace {

using InitWithFrame = void* (*)(void*, SEL, CGRect);
InitWithFrame inherited_init_with_frame = nullptr;

// Plain pointers on purpose: ARC must not retain or release around an initializer (the inherited init consumes
// self and returns a +1 object, which this passes through unchanged).
void* sdl_window_init_with_frame(void* self, SEL cmd, CGRect frame) {
    void* window = inherited_init_with_frame(self, cmd, frame);
    UIWindowScene* scene = ksphmi_scene;
    if (window && scene) ((__bridge UIWindow*)window).windowScene = scene;
    return window;
}

void hook_sdl_window_init() {
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        Class cls = NSClassFromString(@"SDL_uikitwindow");
        SEL sel = @selector(initWithFrame:);
        Method inherited = cls ? class_getInstanceMethod(cls, sel) : nullptr;
        if (!inherited) {
            NSLog(@"KSP HMI: SDL_uikitwindow not found, SDL windows will not get a scene");
            return;
        }
        inherited_init_with_frame = reinterpret_cast<InitWithFrame>(method_getImplementation(inherited));
        // SDL_uikitwindow does not override -initWithFrame: (SDL 2.32.10), so this adds an override to SDL's
        // class only; if a later SDL does override it, replace that implementation instead.
        IMP imp = reinterpret_cast<IMP>(sdl_window_init_with_frame);
        if (!class_addMethod(cls, sel, imp, method_getTypeEncoding(inherited)))
            inherited_init_with_frame = reinterpret_cast<InitWithFrame>(method_setImplementation(inherited, imp));
    });
}

}  // namespace

@interface KSPHMISceneDelegate : UIResponder <UIWindowSceneDelegate>
@property(strong, nonatomic) UIWindow* window;  // UIWindowSceneDelegate; SDL owns the real one
@end

@implementation KSPHMISceneDelegate

- (void)scene:(UIScene*)scene
    willConnectToSession:(UISceneSession*)session
                 options:(UISceneConnectionOptions*)connectionOptions {
    UIWindowScene* windowScene = [scene isKindOfClass:UIWindowScene.class] ? (UIWindowScene*)scene : nil;
    if (!windowScene) return;
    ksphmi_scene = windowScene;
    hook_sdl_window_init();
    // SDL's app delegate answers -window with its first SDL window (nil before SDL_CreateWindow).
    id<UIApplicationDelegate> app = UIApplication.sharedApplication.delegate;
    UIWindow* existing = [app respondsToSelector:@selector(window)] ? app.window : nil;
    if (existing && existing.windowScene != windowScene) {
        existing.windowScene = windowScene;
        if (!existing.hidden) [existing makeKeyAndVisible];
        NSLog(@"KSP HMI: attached the existing SDL window to the scene");
    }
}

- (void)sceneDidDisconnect:(UIScene*)scene {
    if (scene == ksphmi_scene) ksphmi_scene = nil;
}

@end

// --- Safe area (hmi-cpp/include/safearea.hpp) ------------------------------------------------------------------
// main.cpp's Output asks for the insets at start, after every SIZE_CHANGED (rotation), on foreground resume and
// once per frame (a turn between the two landscape orientations moves the island without a size change), so
// they are read from UIKit at call time, never cached. SDL's window is created with SDL_WINDOW_ALLOW_HIGHDPI,
// for which SDL's Metal/GL views use the screen's nativeScale as contentScaleFactor: points * nativeScale =
// drawable pixels. Rounded up, so nothing is drawn under the covered edge.
extern "C" void ksphmi_platform_safe_insets(int* left, int* top, int* right, int* bottom) {
    *left = *top = *right = *bottom = 0;
    if (!NSThread.isMainThread) return;  // UIKit: SDL_main runs on the main thread on iOS
    @autoreleasepool {
        id<UIApplicationDelegate> app = UIApplication.sharedApplication.delegate;
        UIWindow* window = [app respondsToSelector:@selector(window)] ? app.window : nil;  // SDL's first window
        if (!window) {
            UIWindowScene* scene = ksphmi_scene;
            window = scene ? scene.keyWindow : nil;
        }
        if (!window) return;
        const UIEdgeInsets insets = window.safeAreaInsets;
        const CGFloat scale = window.screen ? window.screen.nativeScale : 1.0;
        *left = static_cast<int>(std::ceil(insets.left * scale));
        *top = static_cast<int>(std::ceil(insets.top * scale));
        *right = static_cast<int>(std::ceil(insets.right * scale));
        *bottom = static_cast<int>(std::ceil(insets.bottom * scale));
    }
}
